"""
寻找水仙花数。
说明：水仙花数也被称为超完全数字不变数、自恋数、自幂数、阿姆斯特朗数，它是一个3位数，该数字每个位上数字的立方之和正好等于它本身，例如：$ 153=1^3+5^3+3^3 $。
"""

for num in range(100, 1000):
    # n1 = num % 10
    # n2 = (num - n1) / 10 % 10
    # n3 = (num - n1 - n2 * 10) / 100
    n1 = num % 10
    n2 = num // 10 % 10
    n3 = num // 100
    if n1**3 + n2**3 + n3**3 == num:
        print(num)
